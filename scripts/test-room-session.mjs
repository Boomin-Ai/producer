import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source = await fs.readFile(new URL('../src/lib/roomSession.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020 } }).outputText;
const { roomSession } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const events = [];
let finishRestore;
const old = roomSession();
const restore = old.run(async () => {
  events.push('restore-start');
  await new Promise(resolve => { finishRestore = resolve; });
  events.push('restore-end');
});
await new Promise(resolve => setTimeout(resolve, 0));
const stale = old.run(async () => events.push('stale-restore'));
const close = old.close(async () => events.push('release-capture'));
await old.close(async () => events.push('duplicate-release'));
const next = roomSession();
const reopen = next.run(async () => events.push('new-room-restore'));
finishRestore();
await Promise.all([restore, stale, close, reopen]);
assert.deepEqual(events, ['restore-start', 'restore-end', 'release-capture', 'new-room-restore']);
await assert.rejects(next.close(async () => { throw Error('engine disconnected'); }));
const recovered = roomSession();
await recovered.run(async () => events.push('recovered'));
assert.equal(events.at(-1), 'recovered');
await recovered.close(async () => {});
console.log('PASS: room leave drains restoration, skips stale work, releases capture before reopening, and recovers after errors.');
