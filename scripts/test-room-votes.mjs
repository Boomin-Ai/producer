import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source = await fs.readFile(new URL('../src/lib/roomVotes.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText;
const {activeRoomVote, mergeRoomVote} = await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const old = {id:'old', type:'vote', state:'collecting', version:1, timing:{opened_at:'2026-09-14T00:00:00Z'}};
const recent = {...old, id:'recent', timing:{opened_at:'2026-09-18T00:00:00Z'}};
assert.equal(activeRoomVote([recent, old]).id, 'recent');
assert.equal(activeRoomVote([old, recent]).id, 'recent');
const votes = new Map();
mergeRoomVote(votes, recent, true);
mergeRoomVote(votes, {...recent, tally:{total:2}});
mergeRoomVote(votes, recent, true);
assert.equal(votes.get('recent').tally.total, 2, 'A delayed snapshot must not erase a same-version running tally');
mergeRoomVote(votes, {...recent, state:'cancelled', version:2});
mergeRoomVote(votes, recent, true);
assert.equal(activeRoomVote([...votes.values()]), null, 'A stale snapshot must not revive a cancelled vote');
assert.equal(activeRoomVote([{...old,state:'draft'}]), null);
console.log('Room vote restoration, ordering, running tally, and cancellation checks passed');
