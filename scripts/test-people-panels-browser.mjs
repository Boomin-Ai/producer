import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { build } from 'esbuild';
const { chromium, webkit } = await import(process.env.PRODUCER_PLAYWRIGHT_MODULE ?? '/private/tmp/rene-browser/node_modules/playwright/index.mjs');
const origin = process.env.PRODUCER_PREVIEW_ORIGIN ?? 'http://127.0.0.1:1420';
const output = '/private/tmp/producer-people-panels';
await mkdir(output,{recursive:true});
const bundle = await build({entryPoints:['src/lib/layout.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {normalize,PANEL_META,PRESETS,PANEL_ORDER} = await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
for (const preset of PRESETS) assert.deepEqual(normalize(preset.layout),preset.layout);
const old = {top:['chat'],left:['guests','vote'],right:['sources'],bottom:['mixer'],hidden:['scenes','channels','mods','stats','updates','dj','setControls']};
assert.deepEqual(normalize(old),old,'Consolidation must preserve saved positions and hidden panels');
assert.equal(new Set(Object.values(normalize(old)).flat()).size,PANEL_ORDER.length);
assert.equal(PANEL_META.guests.title,'People'); assert.equal(PANEL_META.vote.title,'Interactions');
for (const [name,engine,options] of [['chromium',chromium,{channel:'chrome'}],['webkit',webkit,{}]]) {
  const browser = await engine.launch({headless:true,...options});
  try {
    const page = await browser.newPage({viewport:{width:1100,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    const calls=async()=>JSON.parse(await page.locator('#calls').textContent());
    await page.goto(`${origin}/scripts/people-panels-browser.html`);
    const people=page.locator('.people-panel');
    const interactions=page.getByRole('region',{name:'Interactions',exact:true});
    await people.locator('.people-join > summary').click();
    await people.getByText('Guest invite',{exact:true}).waitFor();
    assert.ok(await people.locator('.rm-guest-list').evaluate(list => {
      const box = list.getBoundingClientRect();
      return [...list.querySelectorAll('.rm-gcard')].every(card => card.getBoundingClientRect().bottom <= box.bottom + 1);
    }), 'Waiting rows must not push guest thumbnails and names outside their roster');
    await people.getByText('Watch the room, set or show. Chat & interact.',{exact:true}).waitFor();
    await people.getByRole('button',{name:'What is audience access?'}).click();
    await people.getByText(/An active set or show is included in that same feed/).waitFor();
    await people.getByText(/Their camera and microphone stay off until they join as a guest/).waitFor();
    await people.getByRole('button',{name:'What is audience access?'}).click();
    await people.getByRole('button',{name:'What is a guest invite?'}).click();
    await people.getByText(/The host chooses when their media appears/).waitFor();
    await people.getByRole('button',{name:'What is a guest invite?'}).click();
    assert.equal(await people.locator('.rm-vote').count(),0,'People has no embedded poll');
    assert.equal(await interactions.locator('.aud-panel').count(),0,'Interactions has no audience access controls');
    assert.equal(await people.getByRole('textbox').count(),0,'Chat composition stays in Chat');
    await people.getByRole('button',{name:'Copy guest link',exact:true}).click();
    await people.getByRole('button',{name:'Copy audience link',exact:true}).click();
    assert.deepEqual((await calls()).slice(0,2),['copy-guest','copy-audience']);
    await people.getByRole('checkbox',{name:'Audience access'}).uncheck();
    assert.equal((await calls()).at(-1).enabled,false);
    await people.getByRole('checkbox',{name:'Audience access'}).check();
    await people.getByText('Video delivery',{exact:false}).click();
    await people.getByRole('combobox',{name:'Video viewer limit'}).selectOption('1');
    await people.getByText('1 video viewer',{exact:true}).waitFor();
    assert.deepEqual((await calls()).at(-1),{type:'audience.configure',enabled:true,direct_limit:1});
    await people.getByText(/separate from guests sending camera and microphone/).waitFor();
    await people.getByRole('button',{name:'Share audience link on social'}).click();
    await people.getByRole('link',{name:'X',exact:true}).click();
    assert.equal((await calls()).at(-1),'https://x.com/');
    await people.getByRole('button',{name:'Invite to backstage',exact:true}).click();
    assert.deepEqual((await calls()).at(-1),{type:'invite',id:'viewer-one'});
    await people.getByLabel('More actions for Jordan').click();
    await people.getByRole('button',{name:'Mute chat',exact:true}).click();
    assert.deepEqual((await calls()).at(-1),{type:'audience.moderate',id:'viewer-one',action:'mute'});
    const guests=people.getByRole('region',{name:'Guests',exact:true});
    await guests.getByRole('button',{name:'Admit',exact:true}).click();
    assert.ok((await calls()).some(c=>c.type==='admit'&&c.id==='waiting-one'));
    const card=guests.locator('.rm-gcard').filter({hasText:'Alex'});
    await card.hover(); await card.getByRole('button',{name:'Show',exact:true}).click();
    assert.equal((await calls()).at(-1).visible,true);
    await card.getByTitle('Mute',{exact:true}).click();
    assert.equal((await calls()).at(-1).muted,true);
    await interactions.getByRole('button',{name:'Set up',exact:true}).click();
    await interactions.getByPlaceholder('Question (optional)').fill('Who wins?');
    await interactions.getByPlaceholder('Option A').fill('Alex');
    await interactions.getByPlaceholder('Option B').fill('Jordan');
    await interactions.getByRole('button',{name:'Open vote',exact:true}).click();
    assert.deepEqual((await calls()).at(-1),{type:'vote.open',a:'Alex',b:'Jordan',prompt:'Who wins?',who:'both'});
    await interactions.getByText('Collecting',{exact:true}).waitFor();
    await interactions.getByRole('button',{name:'Reveal',exact:true}).click();
    await interactions.getByText('Revealed',{exact:true}).waitFor();
    await interactions.getByRole('button',{name:'Close',exact:true}).click();
    assert.equal((await calls()).at(-1).transition,'close');
    await page.screenshot({path:`${output}/${name}-side.png`});
    await page.getByRole('button',{name:'Make read-only'}).click();
    assert.equal(await people.getByRole('checkbox').count(),0);
    assert.equal(await people.getByRole('button',{name:'Invite to backstage',exact:true}).count(),0);
    assert.equal(await people.getByRole('button',{name:'Copy guest link',exact:true}).count(),0);
    assert.equal(await people.getByLabel('More actions for Jordan').count(),0);
    assert.equal(await interactions.count(),0);
    await people.getByText('Open',{exact:true}).waitFor();
    await page.goto(`${origin}/scripts/people-panels-browser.html?dock=bottom`);
    await page.setViewportSize({width:1200,height:650});
    await page.locator('.people-panel').waitFor();
    await people.locator('.people-join > summary').click();
    assert.ok(await page.locator('.people-panel').evaluate(el=>el.scrollWidth<=el.clientWidth),'Wide bottom dock fits');
    await people.getByRole('button',{name:'What is audience access?'}).click();
    await people.locator('.aud-settings > summary').click();
    assert.ok(await page.locator('.people-join').evaluate(el=>el.scrollHeight>el.clientHeight),'Long joining details scroll inside their column');
    await page.screenshot({path:`${output}/${name}-bottom.png`});
    await page.goto(`${origin}/scripts/people-panels-browser.html?dock=top&mini`);
    await people.getByRole('button',{name:'Join links',exact:true}).click();
    await page.getByRole('button',{name:'Copy audience link',exact:true}).click();
    assert.equal((await calls()).at(-1),'copy-audience');
    await page.keyboard.press('Escape');
    await people.getByRole('button',{name:'Requests · 1',exact:true}).click();
    await page.getByRole('button',{name:'Invite to backstage',exact:true}).click();
    assert.equal((await calls()).at(-1).id,'viewer-one');
    await page.keyboard.press('Escape');
    assert.ok(await people.evaluate(el=>el.scrollWidth<=el.clientWidth),'Mini dock fits');
    await page.screenshot({path:`${output}/${name}-mini.png`});
    await page.goto(`${origin}/scripts/people-panels-browser.html?role=mod`);
    await people.locator('.people-join > summary').click();
    await people.getByText('Ask the host for a guest invitation.').waitFor();
    assert.equal(await people.getByRole('checkbox').count(),0,'Mods cannot configure audience delivery');
    await people.locator('.rm-gcard').hover();
    await people.getByRole('button',{name:'Stage',exact:true}).click();
    assert.deepEqual((await calls()).at(-1),{type:'stage',id:'admitted-one'});
    await people.getByRole('button',{name:'On stage',exact:true}).waitFor();
    await page.setViewportSize({width:360,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Narrow dock fits');
    // Real side dock floor is 200px, independent of the window's width.
    for (const role of ['host','mod']) for (const width of [200,201,240,320]) {
      await page.setViewportSize({width:1100,height:1000});
      await page.goto(`${origin}/scripts/people-panels-browser.html?width=${width}&role=${role}`);
      await people.locator('.people-join > summary').click();
      const checkFits = async () => assert.deepEqual(await people.evaluate(panel => {
        const failures=[];
        for (const el of [panel,...panel.querySelectorAll('.people-join-content,.aud-controls,.aud-header,.aud-share-actions,.aud-settings,.people-roster,.rm-guest.waiting')]) {
          if (el.scrollWidth > el.clientWidth + 1) failures.push(`${el.className} overflows`);
        }
        const header=panel.querySelector('.aud-header');
        const group=header.querySelector('.aud-access-group').getBoundingClientRect();
        const count=header.querySelector('.aud-count').getBoundingClientRect();
        if (group.right > count.left + 1 && group.bottom > count.top + 1) failures.push('Audience label overlaps count');
        for (const button of panel.querySelectorAll('.aud-share-actions button')) {
          const range=document.createRange();range.selectNodeContents(button);
          const label=range.getBoundingClientRect(), bounds=button.getBoundingClientRect();
          if (label.left < bounds.left - 1 || label.right > bounds.right + 1) failures.push('Share action content escapes button');
        }
        return failures;
      }),[],`${name} ${role} ${width}px dock fits`);
      await checkFits();
      await people.getByRole('button',{name:'What is audience access?'}).click();
      await people.getByRole('button',{name:'What is a guest invite?'}).click();
      await people.getByRole('button',{name:'Share audience link on social'}).click();
      if (role === 'host') await people.locator('.aud-settings > summary').click();
      await checkFits();
      await people.getByRole('button',{name:'Copy audience link',exact:true}).click();
      assert.equal((await calls()).at(-1),'copy-audience');
      if (width === 200) {
        await people.getByRole('button',{name:'What is audience access?'}).click();
        await people.getByRole('button',{name:'What is a guest invite?'}).click();
        await people.getByRole('button',{name:'Share audience link on social'}).click();
        if (role === 'host') await people.locator('.aud-settings > summary').click();
        await people.evaluate(panel=>{panel.scrollTop=0});
        await page.locator('.rm-panel-guests').screenshot({path:`${output}/${name}-${role}-minimum.png`});
      }
    }
    await page.goto(`${origin}/scripts/people-panels-browser.html?role=mod&admit-only`);
    await people.getByRole('button',{name:'Admit',exact:true}).waitFor();
    assert.equal(await people.getByRole('button',{name:'Stage',exact:true}).count(),0);
    assert.equal(await people.getByTitle('Remove',{exact:true}).count(),0);
    assert.equal(await people.getByTitle('Move up the order',{exact:true}).count(),0);
    assert.equal(await people.getByLabel('More actions for Jordan').count(),0);
    await page.goto(`${origin}/scripts/moderator-board-browser.html?program&cold`);
    await page.getByRole('button',{name:'People',exact:true}).click();
    await people.locator('.people-join > summary').click();
    await page.getByRole('button',{name:'Copy audience link',exact:true}).click();
    await page.getByRole('button',{name:'Interactions',exact:true}).click();
    await page.getByRole('button',{name:'Open vote',exact:true}).click();
    assert.equal(await page.locator('.mb-operation-content .aud-panel').count(),0);
    await page.getByRole('button',{name:'Chat',exact:true}).click();
    await page.getByText('Shared room chat',{exact:true}).waitFor();
    assert.ok(await page.evaluate(()=>window.moderatorCalls.includes('vote')));
    await page.goto(`${origin}/scripts/moderator-board-browser.html?readonly`);
    assert.equal(await page.getByRole('button',{name:'Interactions',exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Invite to backstage',exact:true}).count(),0);
    assert.deepEqual(errors,[]);
    console.log(`PASS: ${name} People joining, delivery, requests, guest media/admission, standalone poll, permission gates and side/bottom/mini/moderator views.`);
  } finally { await browser.close(); }
}
