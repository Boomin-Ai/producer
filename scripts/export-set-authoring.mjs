#!/usr/bin/env node
/** Reproducible hosted artifact from the canonical Producer generator + validator.
 * Usage: node scripts/export-set-authoring.mjs /path/to/api/src/sets/generated
 */
import {build,version as esbuildVersion} from 'esbuild';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve,relative,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),output=process.argv[2];
if(!output)throw Error('Pass an explicit hosted generated artifact directory.');
const sha256=value=>createHash('sha256').update(value).digest('hex');
const entry="export {authorSet,parseSetAuthoringInput,AUTHORING_BASE_BYTES,AUTHORING_PROMPT_LIMIT} from './server/src/dataIntegrations/setAuthoring';export {ProviderError as AuthoringProviderError} from './server/src/dataIntegrations/providers';";
const options={bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'none'};
const result=await build({...options,absWorkingDir:root,stdin:{contents:entry,resolveDir:root,sourcefile:'set-authoring-entry.ts'},write:false,metafile:true});
const sourceFiles={};for(const input of Object.keys(result.metafile.inputs).sort())if(input!=='set-authoring-entry.ts')sourceFiles[relative(root,resolve(root,input)).replaceAll('\\','/')]=sha256(await readFile(resolve(root,input)));
const module='// Generated by Producer scripts/export-set-authoring.mjs. Do not edit.\n'+result.outputFiles[0].text;
const declaration=`// Generated public boundary; package contents passed the canonical Producer validator.
import type {Connection} from '../providers';
export declare const AUTHORING_BASE_BYTES:number;
export declare const AUTHORING_PROMPT_LIMIT:number;
export declare class AuthoringProviderError extends Error {code:string;constructor(code:string,message:string)}
export interface SetAuthoringInput {prompt:string;package?:Record<string,unknown>}
export interface SetAuthoringResult {package:Record<string,unknown>;provider:'anthropic';model:string}
export declare function parseSetAuthoringInput(value:unknown):SetAuthoringInput;
export declare function authorSet(connection:Connection,key:string,value:unknown,options?:{signal?:AbortSignal;fetcher?:typeof fetch}):Promise<SetAuthoringResult>;
`;
const manifest={generator:'producer/scripts/export-set-authoring.mjs',esbuildVersion,options,sourceHash:sha256(JSON.stringify({entry,options,sourceFiles})),sourceFiles,artifacts:{'set-authoring.mjs':sha256(module),'set-authoring.d.mts':sha256(declaration)}};
const out=resolve(output);await mkdir(out,{recursive:true});for(const [name,contents]of Object.entries({'set-authoring.mjs':module,'set-authoring.d.mts':declaration,'set-authoring.manifest.json':JSON.stringify(manifest,null,2)+'\n'}))await writeFile(resolve(out,name),contents);
console.log(`Exported canonical Set authoring (${Buffer.byteLength(module)} bytes; source ${manifest.sourceHash}).`);
