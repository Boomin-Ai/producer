import assert from 'node:assert/strict';
const { chromium, webkit } = await import(process.env.PRODUCER_PLAYWRIGHT_MODULE ?? '/private/tmp/rene-browser/node_modules/playwright/index.mjs');
const origin = process.env.PRODUCER_PREVIEW_ORIGIN ?? 'http://127.0.0.1:1420';
for (const [name, engine, options] of [['chromium', chromium, { channel: 'chrome' }], ['webkit', webkit, {}]]) {
  const browser = await engine.launch({ headless: true, ...options });
  try {
    const page = await browser.newPage({ viewport: { width: 900, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${origin}/scripts/room-chat-browser.html`);
    const chat = page.locator('.room-chat');
    const frames = async () => JSON.parse(await page.locator('#frames').textContent());
    assert.equal(await page.locator('.aud-chat').count(), 0);
    assert.equal(await page.locator('.aud-panel input[placeholder*="Message"]').count(), 0);
    assert.deepEqual(await chat.locator('.rm-chat-msg').evaluateAll(rows => rows.map(row => [row.dataset.channel, row.querySelector('.rm-chat-user').textContent, row.querySelector('.rm-chat-text').textContent])), [['boomin', 'Host', 'Welcome'], ['twitch', 'Taylor', 'Twitch hello'], ['boomin', 'Jordan', 'Room hello']]);
    await chat.getByRole('button', { name: 'Boomin', exact: true }).click();
    assert.equal(await chat.getByText('Room hello', { exact: true }).count(), 0);
    assert.equal(await chat.getByRole('textbox').count(), 0);
    await chat.getByRole('button', { name: 'Twitch', exact: true }).click();
    await chat.getByRole('button', { name: 'Kick', exact: true }).click();
    await chat.getByRole('button', { name: 'YouTube', exact: true }).click();
    await chat.getByText('Choose a chat channel above.').waitFor();
    await chat.getByRole('button', { name: 'Boomin', exact: true }).click();
    await chat.getByRole('textbox').fill('  Host reply  ');
    await chat.getByRole('button', { name: 'Send', exact: true }).click();
    assert.deepEqual((await frames())[0], { type: 'audience.chat', text: 'Host reply' });
    await chat.getByText('Host reply', { exact: true }).waitFor();
    assert.equal(await chat.getByRole('textbox').inputValue(), '');
    assert.equal(await chat.getByRole('button', { name: 'Wait…', exact: true }).isDisabled(), true);
    await chat.getByLabel('Actions for message from Jordan').click();
    await chat.getByRole('button', { name: 'Mute chat', exact: true }).click();
    assert.deepEqual((await frames())[1], { type: 'audience.moderate', id: 'viewer-id', action: 'mute' });
    await chat.getByLabel('Actions for message from Jordan').click();
    await chat.getByRole('button', { name: 'Remove viewer', exact: true }).click();
    assert.equal((await frames())[2].action, 'remove');
    await chat.getByLabel('Actions for message from Jordan').click();
    await chat.getByRole('button', { name: 'Delete message', exact: true }).click();
    assert.deepEqual((await frames())[3], { type: 'audience.moderate', id: 'viewer-id', action: 'delete', message_id: 'viewer' });
    assert.equal(await chat.getByText('Room hello', { exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Server cooldown', exact: true }).click();
    await chat.getByRole('status').getByText('Wait a moment, then try again.').waitFor();
    assert.equal(await page.locator('.aud-panel .aud-error').count(), 0);
    await chat.getByRole('button', { name: 'Dismiss chat notice' }).click();
    await page.getByRole('button', { name: 'Toggle connection' }).click();
    await chat.getByRole('textbox').fill('Keep this draft');
    await chat.getByRole('button', { name: 'Send', exact: true }).click();
    await chat.getByText('Reconnect to the room first.').waitFor();
    assert.equal(await chat.getByRole('textbox').inputValue(), 'Keep this draft');
    await page.getByRole('button', { name: 'Toggle control grant' }).click();
    assert.equal(await chat.getByRole('textbox').count(), 0);
    assert.equal(await chat.locator('.room-chat-actions').count(), 0);
    await page.getByRole('button', { name: 'Receive room message' }).click();
    await chat.getByText('Incoming 2', { exact: true }).waitFor();
    await chat.getByRole('button', { name: 'Twitch', exact: true }).click();
    for (let i = 0; i < 15; i++) await page.getByRole('button', { name: 'Receive room message' }).click();
    await chat.locator('.rm-chat-list').evaluate(element => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')); });
    await page.getByRole('button', { name: 'Receive room message' }).click();
    await chat.getByRole('button', { name: '1 new message', exact: true }).waitFor();
    await chat.getByRole('button', { name: '1 new message', exact: true }).click();
    assert.equal(await chat.locator('.rm-chat-jump').count(), 0);
    const overflow = await chat.evaluate(element => element.scrollWidth > element.clientWidth);
    assert.equal(overflow, false, '300px side dock must not overflow horizontally');
    await page.screenshot({ path: `/private/tmp/${name}-boomin-chat.png` });
    await page.goto(`${origin}/scripts/room-chat-browser.html?mini`);
    await page.getByRole('button', { name: 'Write to Boomin room' }).click();
    await page.getByRole('textbox', { name: 'Message Boomin room' }).fill('Compact reply');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    assert.deepEqual((await frames())[0], { type: 'audience.chat', text: 'Compact reply' });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.room-chat-compose-pop').isVisible(), false);
    await page.getByRole('button', { name: 'Chat channels', exact: true }).click();
    await page.getByRole('button', { name: 'Boomin', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Write to Boomin room' }).count(), 0);
    assert.deepEqual(errors, []);
    console.log(`PASS: ${name} unified chat, channel filters, room send/cooldown, moderation, readonly grant, reconnect draft, scroll following and compact compose.`);
  } finally { await browser.close(); }
}
